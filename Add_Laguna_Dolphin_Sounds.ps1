$enc = New-Object System.Text.UTF8Encoding($false)
foreach ($name in 'PrimeWorldtest.fdp', 'PrimeWorld.fdp') {
    $path = Join-Path $dir $name
    if (-not (Test-Path $path)) { Write-Host "skip (no file): $name"; continue }
    $text = [System.IO.File]::ReadAllText($path, $enc)
    if ($text.Contains('Laguna_DolphinPuddle')) { Write-Host "already patched: $name"; continue }
    Copy-Item $path "$path.before_laguna" -Force
    $nl = "`r`n"
    $text = Insert-After $text ('<filename>sfxnew/FairyWave.wav</filename>' + $nl + '<guid>') '</waveform>' ($waveforms -replace "`r?`n", $nl)
    $text = Insert-After $text '<name>FairyWave</name>' '</event>' ($events -replace "`r?`n", $nl)
    $text = Insert-After $text '<name>/SFX3/FairyWave</name>' '</sounddef>' ($sounddefs -replace "`r?`n", $nl)
    [xml]$check = $text   # throws if the XML got broken
    [System.IO.File]::WriteAllText($path, $text, $enc)
    Write-Host "patched: $name  (backup: $name.before_laguna)"
}
