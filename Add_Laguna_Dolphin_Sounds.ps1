function Insert-After([string]$text, [string]$anchor, [string]$close, [string]$block) {
    $i = $text.IndexOf($anchor)
    if ($i -lt 0) { throw "anchor not found: $anchor" }
    $j = $text.IndexOf($close, $i)
    if ($j -lt 0) { throw "closing tag not found after: $anchor" }
    $j += $close.Length
    return $text.Substring(0, $j) + "`r`n" + $block + $text.Substring($j)
}

